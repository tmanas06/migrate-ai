// ============================================================
// POST /api/generate-pr – PR description generator
// ============================================================
import { NextRequest, NextResponse } from "next/server";
import { generatePRDescription } from "@/lib/ai";
import type { MigrationType, ApiError } from "@/lib/types";

interface GeneratePRRequest {
  migrationType: MigrationType;
  summary: string;
  filesChanged: number;
  linesAdded: number;
  linesRemoved: number;
  breakingChanges: string[];
}

export async function POST(request: NextRequest) {
  let body: GeneratePRRequest | null = null;
  try {
    body = (await request.json()) as GeneratePRRequest;

    const {
      migrationType,
      summary,
      filesChanged,
      linesAdded,
      linesRemoved,
      breakingChanges,
    } = body;

    if (!migrationType || !summary) {
      return NextResponse.json<ApiError>(
        { error: "Missing required fields: migrationType, summary" },
        { status: 400 }
      );
    }

    const prDescription = await generatePRDescription(
      migrationType,
      summary,
      filesChanged,
      linesAdded,
      linesRemoved,
      breakingChanges || []
    );

    return NextResponse.json({ prDescription });
  } catch (error) {
    console.warn("PR description AI generation failed, using fallback template:", error);
    const labels: Record<string, { from: string; to: string }> = {
      "auto": { from: "Legacy", to: "Modern" },
      "react-17-to-19": { from: "React 17", to: "React 19" },
      "jest-to-vitest": { from: "Jest", to: "Vitest" },
      "cjs-to-esm": { from: "CommonJS", to: "ES Modules" },
      "python-2-to-3": { from: "Python 2", to: "Python 3" },
      "rest-to-trpc": { from: "REST API", to: "tRPC" },
      "tailwind-3-to-4": { from: "Tailwind CSS v3", to: "Tailwind CSS v4" },
    };
    const migrationType = body?.migrationType || "auto";
    const summary = body?.summary || "Automated migration applied using MigrateAI.";
    const filesChanged = body?.filesChanged ?? 0;
    const linesAdded = body?.linesAdded ?? 0;
    const linesRemoved = body?.linesRemoved ?? 0;
    const breakingChanges = body?.breakingChanges || [];

    const { from, to } = labels[migrationType] || { from: "Legacy", to: "Modern" };

    const fallbackPR = `## Summary

Automated migration from **${from}** to **${to}** using MigrateAI.

${summary}

## Changes
- Files modified: ${filesChanged}
- Lines added: +${linesAdded}
- Lines removed: -${linesRemoved}

## Breaking Changes
${breakingChanges.length > 0 ? breakingChanges.map((c: string) => `- ⚠️ ${c}`).join("\n") : "- None detected"}

## Testing
- [ ] Run test suite to verify no regressions
- [ ] Verify build passes without errors
- [ ] Smoke test updated components and functions

---
*Generated by [MigrateAI](https://github.com/migrateai)*`;

    return NextResponse.json({ prDescription: fallbackPR });
  }
}
